-- Quiz Craft - Unified exam access/session rules (v2)
-- Run once in Supabase SQL Editor after taking a database backup.
--
-- Rules enforced by the server:
-- 1) PRIVATE blocks all access immediately (including old entry tokens).
-- 2) LOCKED / an elapsed khoa_den blocks NEW sessions.
-- 3) A session issued before LOCKED / khoa_den may resume and submit once.
-- 4) A submitted session cannot be reused to start or save another attempt.
-- 5) DELETED blocks access and submission, regardless of session token.
--
-- This migration deliberately does not change the de_thi table's RLS policies
-- or its project_key unique constraint. Teacher-side de_thi updates still use
-- the existing authenticated Supabase bridge and must be read back/verified.

create table if not exists public.qc_exam_sessions (
  id bigint generated by default as identity primary key,
  entry_token uuid not null default gen_random_uuid() unique,
  teacher_id text not null,
  exam_id text not null,
  student_id text not null,
  class_code text not null,
  started_at timestamptz not null default now(),
  last_active_at timestamptz not null default now(),
  submitted_at timestamptz,
  attempt_id text
);

-- Upgrade an earlier v1 table in-place without deleting existing sessions.
alter table public.qc_exam_sessions
  add column if not exists entry_token uuid default gen_random_uuid(),
  add column if not exists teacher_id text,
  add column if not exists exam_id text,
  add column if not exists student_id text,
  add column if not exists class_code text,
  add column if not exists started_at timestamptz default now(),
  add column if not exists last_active_at timestamptz default now(),
  add column if not exists submitted_at timestamptz,
  add column if not exists attempt_id text;

create unique index if not exists qc_exam_sessions_entry_token_uidx
  on public.qc_exam_sessions (entry_token);
create unique index if not exists qc_exam_sessions_attempt_id_uidx
  on public.qc_exam_sessions (attempt_id)
  where attempt_id is not null;
create index if not exists qc_exam_sessions_exam_idx
  on public.qc_exam_sessions (teacher_id, exam_id, started_at desc);
create index if not exists qc_exam_sessions_student_idx
  on public.qc_exam_sessions (teacher_id, exam_id, student_id, class_code);

alter table public.qc_exam_sessions enable row level security;
revoke all on table public.qc_exam_sessions from public, anon, authenticated;

create or replace function public.qc_begin_exam(
  p_teacher_id text,
  p_exam_id text,
  p_student_id text,
  p_class_code text,
  p_entry_token text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_exam public.de_thi%rowtype;
  v_session public.qc_exam_sessions%rowtype;
  v_status text;
  v_access text;
  v_lock_at timestamptz;
  v_token uuid;
begin
  if coalesce(btrim(p_teacher_id), '') = ''
     or coalesce(btrim(p_exam_id), '') = ''
     or coalesce(btrim(p_student_id), '') = ''
     or coalesce(btrim(p_class_code), '') = '' then
    return jsonb_build_object('ok', false, 'code', 'INVALID_IDENTITY',
      'error', 'Thiếu thông tin nhận diện bài thi hoặc học sinh.');
  end if;

  -- Lock the exam row while checking state and issuing a session. A concurrent
  -- teacher UPDATE waits for this transaction, so the start time is unambiguous.
  select d.* into v_exam
  from public.de_thi d
  where d.id_de::text = btrim(p_exam_id)
    and d.id_gv::text = btrim(p_teacher_id)
  limit 1
  for share;

  if not found then
    return jsonb_build_object('ok', true, 'allowed', false, 'reason', 'missing',
      'code', 'EXAM_NOT_FOUND', 'message', 'Đề thi đã bị xóa hoặc không còn tồn tại trong hệ thống.');
  end if;

  v_status := upper(coalesce(v_exam.trang_thai::text, 'ACTIVE'));
  v_access := upper(coalesce(v_exam.che_do_truy_cap::text, 'PUBLIC'));
  v_lock_at := nullif(btrim(coalesce(v_exam.khoa_den::text, '')), '')::timestamptz;

  if v_status = 'DELETED' then
    return jsonb_build_object('ok', true, 'allowed', false, 'reason', 'deleted',
      'code', 'EXAM_DELETED', 'message', 'Đề thi đã bị xóa.');
  end if;

  -- PRIVATE is not the same as LOCKED: it displays only the access-denied
  -- notice and revokes even an old active token. No local-only continuation.
  if v_access = 'PRIVATE' then
    return jsonb_build_object('ok', true, 'allowed', false, 'reason', 'private',
      'code', 'EXAM_PRIVATE',
      'message', 'Bạn không có quyền truy cập vào file này do người tạo đã bật riêng tư.');
  end if;

  -- Resume only an unsubmitted server-issued session. This lets students who
  -- entered before a lock/deadline continue, but a finished attempt's token
  -- cannot be reused after the exam has been locked.
  if coalesce(btrim(p_entry_token), '') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    select s.* into v_session
    from public.qc_exam_sessions s
    where s.entry_token = btrim(p_entry_token)::uuid
      and s.teacher_id = btrim(p_teacher_id)
      and s.exam_id = btrim(p_exam_id)
      and s.student_id = btrim(p_student_id)
      and s.class_code = btrim(p_class_code)
      and s.submitted_at is null
    limit 1
    for update;

    if found then
      update public.qc_exam_sessions
      set last_active_at = now()
      where entry_token = v_session.entry_token;
      return jsonb_build_object('ok', true, 'allowed', true,
        'entryToken', v_session.entry_token::text, 'resumed', true);
    end if;
  end if;

  -- A request without a valid, unfinished prior session is a NEW entrant.
  if v_status = 'LOCKED' then
    return jsonb_build_object('ok', true, 'allowed', false, 'reason', 'locked',
      'code', 'EXAM_LOCKED', 'message', 'Đề thi đã bị khóa.');
  end if;
  if v_lock_at is not null and v_lock_at <= now() then
    return jsonb_build_object('ok', true, 'allowed', false, 'reason', 'expired',
      'code', 'EXAM_EXPIRED', 'lockedUntil', v_lock_at,
      'message', 'Đề đã hết thời hạn theo lịch khóa của giáo viên.');
  end if;

  if coalesce(btrim(v_exam.ma_lop::text), '') <> ''
     and btrim(v_exam.ma_lop::text) <> btrim(p_class_code) then
    return jsonb_build_object('ok', true, 'allowed', false, 'reason', 'class_mismatch',
      'code', 'EXAM_CLASS_MISMATCH', 'message', 'Đề này được giao cho lớp khác.');
  end if;

  insert into public.qc_exam_sessions (teacher_id, exam_id, student_id, class_code)
  values (btrim(p_teacher_id), btrim(p_exam_id), btrim(p_student_id), btrim(p_class_code))
  returning entry_token into v_token;

  return jsonb_build_object('ok', true, 'allowed', true,
    'entryToken', v_token::text, 'resumed', false);
end;
$$;

create or replace function public.qc_submit_exam(
  p_entry_token text,
  p_teacher_id text,
  p_exam_id text,
  p_student_id text,
  p_student_name text,
  p_class_code text,
  p_attempt_id text,
  p_score numeric,
  p_max_score numeric,
  p_elapsed_seconds integer,
  p_student_email text default '',
  p_guest_id text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_session public.qc_exam_sessions%rowtype;
  v_exam public.de_thi%rowtype;
  v_rows integer;
  v_existing record;
begin
  if coalesce(btrim(p_entry_token), '') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    return jsonb_build_object('ok', false, 'code', 'EXAM_SESSION_INVALID',
      'error', 'Phiên làm bài không hợp lệ. Hãy đăng nhập và vào đề lại.');
  end if;
  if coalesce(btrim(p_attempt_id), '') = ''
     or coalesce(btrim(p_student_name), '') = ''
     or p_score is null or p_score < 0
     or p_max_score is null or p_max_score <= 0
     or coalesce(p_elapsed_seconds, 0) < 0 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_RESULT',
      'error', 'Thông tin kết quả không hợp lệ.');
  end if;

  -- Keep the same lock order as qc_begin_exam (exam row, then session row)
  -- to avoid a lock-order deadlock when a student resumes and submits together.
  select d.* into v_exam
  from public.de_thi d
  where d.id_de::text = btrim(p_exam_id)
    and d.id_gv::text = btrim(p_teacher_id)
  limit 1
  for share;

  if not found or upper(coalesce(v_exam.trang_thai::text, 'ACTIVE')) = 'DELETED' then
    return jsonb_build_object('ok', false, 'code', 'EXAM_DELETED',
      'error', 'Đề đã bị xóa. Kết quả không được lưu.');
  end if;

  -- PRIVATE blocks submission too. LOCKED and an elapsed deadline do not:
  -- the token proves that this student entered while the exam was open.
  if upper(coalesce(v_exam.che_do_truy_cap::text, 'PUBLIC')) = 'PRIVATE' then
    return jsonb_build_object('ok', false, 'code', 'EXAM_PRIVATE',
      'error', 'Bạn không có quyền truy cập vào file này do người tạo đã bật riêng tư.');
  end if;

  select s.* into v_session
  from public.qc_exam_sessions s
  where s.entry_token = btrim(p_entry_token)::uuid
    and s.teacher_id = btrim(p_teacher_id)
    and s.exam_id = btrim(p_exam_id)
    and s.student_id = btrim(p_student_id)
    and s.class_code = btrim(p_class_code)
  limit 1
  for update;

  if not found then
    return jsonb_build_object('ok', false, 'code', 'EXAM_SESSION_INVALID',
      'error', 'Không xác minh được phiên bắt đầu làm bài.');
  end if;

  -- Network retries for an already inserted attempt are idempotent.
  select h.id_luot_lam, h.id_gv, h.id_de, h.id_hs into v_existing
  from public.lich_su h
  where h.id_luot_lam::text = btrim(p_attempt_id)
  limit 1;
  if found then
    if v_existing.id_gv::text = btrim(p_teacher_id)
       and v_existing.id_de::text = btrim(p_exam_id)
       and v_existing.id_hs::text = btrim(p_student_id) then
      update public.qc_exam_sessions
      set submitted_at = coalesce(submitted_at, now()),
          last_active_at = now(),
          attempt_id = coalesce(attempt_id, btrim(p_attempt_id))
      where entry_token = v_session.entry_token;
      return jsonb_build_object('ok', true, 'duplicate', true,
        'studentId', btrim(p_student_id), 'attemptId', btrim(p_attempt_id));
    end if;
    return jsonb_build_object('ok', false, 'code', 'ATTEMPT_CONFLICT',
      'error', 'Mã lượt làm đã được dùng cho một kết quả khác.');
  end if;

  if v_session.submitted_at is not null then
    return jsonb_build_object('ok', false, 'code', 'SESSION_ALREADY_SUBMITTED',
      'error', 'Phiên này đã nộp bài. Muốn làm lại, hãy bắt đầu lượt mới khi đề còn mở.');
  end if;

  insert into public.lich_su (
    id_luot_lam, id_gv, id_de, id_hs, ten_hoc_sinh, ma_lop,
    diem, diem_toi_da, thoi_luong_giay, email_hs, guest_id,
    thoi_gian_nop, trang_thai
  ) values (
    btrim(p_attempt_id), btrim(p_teacher_id), btrim(p_exam_id), btrim(p_student_id),
    btrim(p_student_name), btrim(p_class_code), p_score, p_max_score,
    greatest(0, coalesce(p_elapsed_seconds, 0)), coalesce(p_student_email, ''),
    coalesce(p_guest_id, ''), now(), 'SAVED'
  ) on conflict (id_luot_lam) do nothing;

  get diagnostics v_rows = row_count;
  if v_rows = 0 then
    return jsonb_build_object('ok', false, 'code', 'ATTEMPT_CONFLICT',
      'error', 'Không thể ghi nhận lượt làm trùng mã.');
  end if;

  update public.qc_exam_sessions
  set submitted_at = now(), last_active_at = now(), attempt_id = btrim(p_attempt_id)
  where entry_token = v_session.entry_token;

  return jsonb_build_object('ok', true,
    'studentId', btrim(p_student_id), 'attemptId', btrim(p_attempt_id));
end;
$$;

revoke all on function public.qc_begin_exam(text, text, text, text, text) from public;
revoke all on function public.qc_submit_exam(text, text, text, text, text, text, text, numeric, numeric, integer, text, text) from public;
grant execute on function public.qc_begin_exam(text, text, text, text, text) to anon, authenticated;
grant execute on function public.qc_submit_exam(text, text, text, text, text, text, text, numeric, numeric, integer, text, text) to anon, authenticated;

comment on table public.qc_exam_sessions is
  'Quiz Craft server-issued sessions: PRIVATE revokes access; LOCKED/deadline blocks new sessions while unfinished sessions started earlier may submit once.';

notify pgrst, 'reload schema';
